#!/usr/bin/env python3
"""Generates ios/App/App/Plugins/SleepMessageBank.swift from the Android MessageBank.java.

The Android bank is the source of truth for Sleep Mode's reminder lines. Run this after editing
it so the iOS app speaks the same lines:

    python3 scripts/gen-sleep-message-bank.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
JAVA = ROOT / "android/app/src/main/java/com/syhuinc/omnihub/sleepmode/MessageBank.java"
SWIFT = ROOT / "ios/App/App/Plugins/SleepMessageBank.swift"

PERSONALITIES = ["gentle", "friendly", "teasing", "strict", "savage"]
TIERS = 4

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
POOL_3D = re.compile(r"(GENERIC|NAMED)\[(\d)\]\[(\d)\]\s*=\s*new String\[\]\s*\{(.*?)\};", re.S)
POOL_2D = re.compile(r"(WORK_TOMORROW|WAKE_PROXIMITY|INTERESTS)\[(\d)\]\s*=\s*new String\[\]\s*\{(.*?)\};", re.S)


def strip_line_comments(block: str) -> str:
    return "\n".join(line for line in block.splitlines() if not line.strip().startswith("//"))


def to_swift_literal(java_body: str) -> str:
    # Java and Swift share \" \\ \n \t; Swift has no \' escape, so unescape it.
    return '"' + java_body.replace("\\'", "'") + '"'


def literals(block: str):
    return [to_swift_literal(m.group(1)) for m in STRING.finditer(strip_line_comments(block))]


def main() -> int:
    source = JAVA.read_text(encoding="utf-8")

    generic = [[None] * TIERS for _ in PERSONALITIES]
    named = [[None] * TIERS for _ in PERSONALITIES]
    for m in POOL_3D.finditer(source):
        target = generic if m.group(1) == "GENERIC" else named
        target[int(m.group(2))][int(m.group(3))] = literals(m.group(4))

    flat = {"WORK_TOMORROW": [None] * 5, "WAKE_PROXIMITY": [None] * 5, "INTERESTS": [None] * 5}
    for m in POOL_2D.finditer(source):
        flat[m.group(1)][int(m.group(2))] = literals(m.group(3))

    for p in range(len(PERSONALITIES)):
        for t in range(TIERS):
            if not generic[p][t] or not named[p][t]:
                sys.exit(f"MessageBank.java: missing pool for personality {p} tier {t}")
        for name, pools in flat.items():
            if not pools[p]:
                sys.exit(f"MessageBank.java: missing {name}[{p}]")

    def fmt_3d(pools):
        out = []
        for p, personality in enumerate(PERSONALITIES):
            out.append(f"        // {personality}")
            out.append("        [")
            for t in range(TIERS):
                out.append(f"            [ // tier {t}")
                out.extend(f"                {line}," for line in pools[p][t])
                out.append("            ],")
            out.append("        ],")
        return "\n".join(out)

    def fmt_2d(pools):
        out = []
        for p, personality in enumerate(PERSONALITIES):
            out.append(f"        [ // {personality}")
            out.extend(f"            {line}," for line in pools[p])
            out.append("        ],")
        return "\n".join(out)

    PERSONALITY_LITERALS = ", ".join(f'"{p}"' for p in PERSONALITIES)
    swift = f'''// Generated by scripts/gen-sleep-message-bank.py from
// android/app/src/main/java/com/syhuinc/omnihub/sleepmode/MessageBank.java.
// Do not edit by hand: change the Java bank (the source of truth) and re-run the script.
import Foundation

/// Sleep Mode's reminder lines, keyed by personality and escalation tier (0 = right at bedtime,
/// 3 = maximally persistent), with the same pools and pick rules as the Android MessageBank.
enum SleepMessageBank {{
    static let personalities = [{PERSONALITY_LITERALS}]
    static let tierCount = {TIERS}

    struct Pick {{
        let text: String
        let key: String
    }}

    /// Picks one line for the personality/tier, avoiding `recentKeys` when possible and falling
    /// back to the full pool only once every candidate has been used recently. `aiPool` is the
    /// cached AI-generated pool for this personality, indexed [tier][line], or nil.
    static func pick(
        personality: String,
        tier: Int,
        displayName: String?,
        hasWorkTomorrow: Bool,
        interests: String?,
        wakeTimeLabel: String?,
        recentKeys: Set<String>,
        aiPool: [[String]]?
    ) -> Pick {{
        let p = personalities.firstIndex(of: personality) ?? 1 // friendly
        let t = max(0, min(tierCount - 1, tier))
        let name = (displayName ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        let interestText = (interests ?? "").trimmingCharacters(in: .whitespacesAndNewlines)

        var pools: [[String]] = [generic[p][t]]
        var prefixes: [String] = ["g\\(t)"]
        if let ai = aiPool, ai.count > t, !ai[t].isEmpty {{
            pools.append(ai[t])
            prefixes.append("ai\\(t)")
        }}
        if !name.isEmpty {{
            pools.append(named[p][t])
            prefixes.append("n\\(t)")
        }}
        if t >= 1 && hasWorkTomorrow {{
            pools.append(workTomorrow[p])
            prefixes.append("w")
        }}
        if t >= 1, let wake = wakeTimeLabel, !wake.isEmpty {{
            pools.append(wakeProximity[p])
            prefixes.append("k")
        }}
        if t >= 1 && !interestText.isEmpty {{
            pools.append(interestLines[p])
            prefixes.append("i")
        }}

        var keys: [String] = []
        var texts: [String] = []
        for (i, pool) in pools.enumerated() {{
            for (j, line) in pool.enumerated() {{
                keys.append("\\(personality):\\(prefixes[i]):\\(j)")
                texts.append(line)
            }}
        }}

        let fresh = keys.indices.filter {{ !recentKeys.contains(keys[$0]) }}
        let candidates = fresh.isEmpty ? Array(keys.indices) : fresh
        let chosen = candidates[Int.random(in: 0..<candidates.count)]
        let text = texts[chosen]
            .replacingOccurrences(of: "{{name}}", with: name)
            .replacingOccurrences(of: "{{wakeTime}}", with: wakeTimeLabel ?? "")
            .replacingOccurrences(of: "{{interests}}", with: interestText)
        return Pick(text: text, key: keys[chosen])
    }}

    // [personality][tier] -> lines without a name
    static let generic: [[[String]]] = [
{fmt_3d(generic)}
    ]

    // [personality][tier] -> lines with exactly one {{name}} placeholder
    static let named: [[[String]]] = [
{fmt_3d(named)}
    ]

    // [personality] -> bonus lines when the user has work/school tomorrow (tier >= 1 only)
    static let workTomorrow: [[String]] = [
{fmt_2d(flat["WORK_TOMORROW"])}
    ]

    // [personality] -> bonus lines once a wake time is known (tier >= 1 only), uses {{wakeTime}}
    static let wakeProximity: [[String]] = [
{fmt_2d(flat["WAKE_PROXIMITY"])}
    ]

    // [personality] -> bonus lines when Interests is set (tier >= 1 only), uses {{interests}}
    static let interestLines: [[String]] = [
{fmt_2d(flat["INTERESTS"])}
    ]
}}
'''
    SWIFT.write_text(swift, encoding="utf-8")
    total = sum(len(generic[p][t]) + len(named[p][t]) for p in range(5) for t in range(TIERS))
    total += sum(len(pools[p]) for pools in flat.values() for p in range(5))
    print(f"wrote {SWIFT.relative_to(ROOT)} ({total} lines of copy)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
